/**
 * Random Atmosphere Image Selector with Persistent Anti-Repetition Ring Buffer
 * @param {string} atmosphereKey Visual atmosphere key (ocean, rain, night, mistyMountains, vintage, deepOcean, foggyForest)
 * @param {Array<string>} customHistory Optional in-memory history array of recently seen photo IDs
 * @returns {Object} Selected photorealistic image object
 */
export function getRandomAtmosphereImage(atmosphereKey = 'ocean', customHistory = null) {
  const list = saudadeAtmospheres[atmosphereKey] || saudadeAtmospheres.ocean;

  // Retrieve persistent photo history from localStorage if not explicitly passed
  let history = customHistory;
  if (!history) {
    try {
      history = JSON.parse(localStorage.getItem('taskflow-saudade-photo-history') || '[]');
    } catch (e) {
      history = [];
    }
  }

  // Filter out recently seen photo IDs
  let candidates = list.filter((item) => !history.includes(item.id));
  if (candidates.length === 0) {
    candidates = list;
  }

  const randomIndex = Math.floor(Math.random() * candidates.length);
  const selectedImage = candidates[randomIndex];

  // Update persistent history buffer (up to 35 items)
  try {
    const updatedHistory = [...history.filter((id) => id !== selectedImage.id), selectedImage.id];
    if (updatedHistory.length > 35) {
      updatedHistory.shift();
    }
    localStorage.setItem('taskflow-saudade-photo-history', JSON.stringify(updatedHistory));
  } catch (e) {
    // Ignore storage quota errors
  }

  return selectedImage;
}
